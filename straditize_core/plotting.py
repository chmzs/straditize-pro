"""本机一键出图：探测 Rscript、生成 rioja 脚本、跑出 PDF/PNG。

## 为什么单开一个模块

出图有三条路（本机 R / Python 复刻 / riojaPlot 网页），三者的**数据来源必须是同一个**：
ExportMixin._primary_roi_export_frame（= data.csv 那一张表）。任何一条自己拼表，
用户就会拿到画出来和图不一样的数据。

## 不静默降级（ARCHITECTURE §2）

R 找不到 / R 跑失败 / rioja 没装，都必须把「缺什么、怎么补」原样交给调用方，
不许退回到一张空白图或空文件——那看起来像「这张图没有数据」。
"""

from __future__ import annotations

import os
import shutil
import subprocess
from pathlib import Path
from typing import Any

#: R 的可执行文件名（Windows 带 .exe）。
R_SCRIPT_NAME = "Rscript.exe" if os.name == "nt" else "Rscript"

#: Windows 上 R 的常见安装根目录：扫这里，用户就不必手填路径。
COMMON_R_ROOTS = (
    r"C:\Program Files\R",
    r"C:\Program Files (x86)\R",
    r"D:\Program Files\R",
    r"D:\R",
)


def _rscript_paths_under(root: Path) -> list[str]:
    """列出某个安装根目录下所有 Rscript（新版本排在前面）。"""
    if not root.is_dir():
        return []
    found: list[str] = []
    try:
        children = sorted(root.iterdir(), reverse=True)
    except OSError:
        return []
    for child in children:
        exe = child / "bin"
        if os.name == "nt":
            exe = exe / "x64"
        exe = exe / R_SCRIPT_NAME
        if exe.is_file():
            found.append(str(exe))
    return found


def candidate_rscripts() -> list[str]:
    """所有可验证的 Rscript 候选：PATH 优先，其次常见安装目录。"""
    found: list[str] = []
    seen: set[str] = set()

    def add(path: str | None) -> None:
        if not path:
            return
        key = os.path.normcase(os.path.abspath(path))
        if key in seen:
            return
        seen.add(key)
        found.append(os.path.abspath(path))

    add(shutil.which("Rscript"))
    for root in COMMON_R_ROOTS:
        for exe in _rscript_paths_under(Path(root)):
            add(exe)
    return found


def detect_rscript(explicit: str | None = None) -> dict[str, Any]:
    """定位 Rscript：显式配置 > PATH > 常见安装目录。

    显式配置了但文件不存在时**不回退**自动探测：用户填错路径却拿到「探测成功」，
    下次出图用的是另一个 R（装没装 rioja 都不一样）——这种静默替换比报错难查得多。
    """
    candidates = candidate_rscripts()
    explicit = (explicit or "").strip()
    if explicit:
        path = Path(explicit).expanduser()
        if path.is_file():
            return {
                "path": str(path.resolve()),
                "source": "config",
                "candidates": candidates,
                "error": None,
            }
        return {
            "path": None,
            "source": "config",
            "candidates": candidates,
            "error": (
                f"设置页填写的 Rscript 路径不存在：{explicit}。"
                "请改正路径，或清空该字段改用自动探测。"
            ),
        }
    if candidates:
        return {
            "path": candidates[0],
            "source": "path",
            "candidates": candidates,
            "error": None,
        }
    return {
        "path": None,
        "source": None,
        "candidates": [],
        "error": (
            "未找到 Rscript：本机没有 R（或不在 PATH / 常见安装目录）。"
            "请安装 R（https://cran.r-project.org/，需含 rioja 包），"
            "或在设置页填写 Rscript 可执行文件路径。"
        ),
    }


#: rioja::strat.plot 的驱动脚本。**不做任何插值**：读进来的就是导出的那张表，
#: NA 原样交给 rioja（画成缺口），不替用户补零。
RIOJA_SCRIPT = r'''# Generated by straditize: local stratigraphic plot (rioja::strat.plot)
args <- commandArgs(trailingOnly = TRUE)
csv_path <- args[[1]]
out_path <- args[[2]]
title_text <- args[[3]]

if (!requireNamespace("rioja", quietly = TRUE)) {
  stop("R package rioja is not installed: run install.packages(\"rioja\") in R, then retry.")
}
raw <- read.csv(csv_path, check.names = FALSE, na.strings = c("NA", "", "NaN"))
if (ncol(raw) < 2) stop("The exported table has only the depth column; nothing to plot.")
depth <- raw[[1]]
taxa <- as.matrix(sapply(raw[, -1, drop = FALSE], as.numeric))

ext <- tolower(tools::file_ext(out_path))
if (ext == "png") {
  png(out_path, width = 1800, height = 1300, res = 150)
} else if (ext == "svg") {
  svg(out_path, width = 12, height = 8)
} else {
  pdf(out_path, width = 12, height = 8)
}
rioja::strat.plot(
  d = taxa,
  yvar = depth,
  y.rev = TRUE,
  ylabel = "Depth",
  plot.poly = TRUE,
  plot.line = TRUE,
  title = title_text
)
dev.off()
if (!file.exists(out_path)) stop("R produced no output file: ", out_path)
cat(normalizePath(out_path), "\n")
'''


def render_with_rioja(
    *,
    csv_path: str,
    out_path: str,
    rscript: str,
    title: str = "",
    timeout: float = 180.0,
) -> dict[str, Any]:
    """跑 R 出图；失败时抛 RuntimeError，消息里带 R 自己的 stderr。"""
    out = Path(out_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    script_path = out.with_suffix(".R")
    script_path.write_text(RIOJA_SCRIPT, encoding="utf-8")
    try:
        proc = subprocess.run(
            [rscript, str(script_path), str(Path(csv_path)), str(out), title or ""],
            capture_output=True,
            text=True,
            timeout=timeout,
            check=False,
        )
    except subprocess.TimeoutExpired as exc:
        raise RuntimeError(
            f"R 出图超时（>{timeout:.0f}s）：数据行数过多或 R 进程卡住。{exc}"
        ) from exc
    if proc.returncode != 0 or not out.is_file():
        stderr = (proc.stderr or proc.stdout or "").strip()
        raise RuntimeError(
            f"R 出图失败（返回码 {proc.returncode}）：{stderr or '没有错误输出'}"
        )
    return {
        "path": str(out.resolve()),
        "r_script": str(script_path.resolve()),
        "size_bytes": out.stat().st_size,
        "engine": "rioja",
        "rscript": rscript,
        "command": [rscript, str(script_path), str(csv_path), str(out)],
    }
